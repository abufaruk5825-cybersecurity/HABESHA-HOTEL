const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('habesha_language');
      return (saved === 'am' || saved === 'en') ? saved : 'en';
    } catch {
      return 'en';
    }
  });

  const [calendar, setCalendarState] = useState<CalendarType>(() => {
    try {
      const saved = localStorage.getItem('habesha_calendar');
      return (saved === 'ethiopian' || saved === 'gregorian') ? saved : 'gregorian';
    } catch {
      return 'gregorian';
    }
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('habesha_language', lang);
    } catch (e) {
      console.error(e);
    }
    document.documentElement.lang = lang;
  };

  const setCalendar = (cal: CalendarType) => {
    setCalendarState(cal);
    try {
      localStorage.setItem('habesha_calendar', cal);
    } catch (e) {
      console.error(e);
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language] || TRANSLATIONS.en;
    if (langDict && langDict[key]) return langDict[key];
    const enDict = TRANSLATIONS.en;
    if (enDict && enDict[key]) return enDict[key];
    return fallback || key;
  };

  const formatCurrency = (amount: number | string): string => {
    const num = Number(amount) || 0;
    const formatted = num.toLocaleString('en-US', { minimumFractionDigits: 0, maximumFractionDigits: 2 });
    return language === 'am' ? `${formatted} ብር (ETB)` : `ETB ${formatted}`;
  };

  const formatDate = (date: Date | string): string => {
    return formatHotelDate(date, calendar, language);
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        calendar,
        setCalendar,
        t,
        formatCurrency,
        formatDate,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
